import Link from "next/link";
import { generateSyntheticCohortMetrics } from "@/lib/synthetic-cohort";

export const metadata = { title: "Measurement | OncoNourish", robots: "noindex, nofollow" };

function MetricBar({ label, value, detail, max = 100 }: {
  label: string;
  value: number;
  detail: string;
  max?: number;
}) {
  const width = Math.max(value > 0 ? 1 : 0, Math.min(100, value / max * 100));
  return <div className="bar-row">
    <span>{label}</span>
    <div className="meter" role="img" aria-label={`${label}: ${detail}`}>
      <span style={{ width: `${width}%` }} />
    </div>
    <span className="small muted">{detail}</span>
  </div>;
}

export default function MeasurementPage() {
  const metrics = generateSyntheticCohortMetrics();
  const retentionWeeks = [1, 3, 5].map((week) => metrics.weekly[week - 1]);
  const recoveryMaximum = Math.max(1, ...Object.values(metrics.recoveryHistogram));

  return <main className="app-shell">
    <header className="topbar">
      <Link className="brand" href="/login">OncoNourish</Link>
      <nav className="row" aria-label="Product information">
        <Link className="button small" href="/safety">Safety</Link>
        <Link className="button small" href="/about">About</Link>
      </nav>
    </header>
    <h1>Measurement</h1>
    <section className="banner warning" role="note">
      <strong>Synthetic data generated by this prototype.</strong>
      <p>This seeded {metrics.cohortSize}-person, {metrics.observedDays}-day cohort illustrates metric calculations; it is not evidence of effectiveness or clinical outcomes.</p>
    </section>
    <div className="clinician-grid">
      <section className="card">
        <h2>Persistence by week</h2>
        <p className="muted small">Share of simulated users with check-ins on at least 4 days in that week.</p>
        {metrics.weekly.map(({ week, persistencePercent }) => <MetricBar
          key={week}
          label={`Week ${week}`}
          value={persistencePercent}
          detail={`${persistencePercent.toFixed(0)}%`}
        />)}
      </section>
      <section className="card">
        <h2>Retention</h2>
        <p className="muted small">Share of simulated users with at least one check-in that week.</p>
        {retentionWeeks.map(({ week, retentionPercent }) => <MetricBar
          key={week}
          label={`Week ${week}`}
          value={retentionPercent}
          detail={`${retentionPercent.toFixed(0)}%`}
        />)}
      </section>
      <section className="card">
        <h2>Return after a lapse</h2>
        <p className="muted small">
          {metrics.recoveryGaps.length} simulated gaps of at least two missed days; median missed days before the next check-in: {metrics.medianRecoveryDays}.
        </p>
        {([2, 3, 4, 5, 6, 7] as const).map((days) => <MetricBar
          key={days}
          label={days === 7 ? "7+ missed days" : `${days} missed days`}
          value={metrics.recoveryHistogram[days]}
          max={recoveryMaximum}
          detail={String(metrics.recoveryHistogram[days])}
        />)}
      </section>
    </div>
    <section className="card">
      <h2>Week 6 persistence by language group</h2>
      <p className="muted small">Groups are assigned by the seeded generator; small samples are illustrative only.</p>
      <div className="clinician-table">
        <table>
          <thead><tr><th scope="col">Language group</th><th scope="col">Sample size</th><th scope="col">Persistence</th></tr></thead>
          <tbody>{metrics.byLanguage.map(({ language, sampleSize, weekSixPersistencePercent }) => <tr key={language}>
            <th scope="row">{language}</th>
            <td>{sampleSize}</td>
            <td>{weekSixPersistencePercent.toFixed(0)}%</td>
          </tr>)}</tbody>
        </table>
      </div>
      <p className="muted small">Groups are identical by construction; observed differences are random variation, not evidence of inequity or equity.</p>
    </section>
    <section className="card">
      <h2>Pre-specified metric definitions</h2>
      <ul>
        <li>Persistence: four or more check-in days per seven-day week.</li>
        <li>Retention: at least one check-in in weeks 1, 3, and 5.</li>
        <li>Return after a lapse: count of consecutive missed days before a later check-in, for gaps of at least two days.</li>
        <li>Equity: week 6 persistence grouped by generated language assignment.</li>
        <li>Downloads, taps, and messages are not outcomes.</li>
      </ul>
    </section>
    <footer className="muted">Synthetic data only · Illustrative metrics · Not clinical evidence</footer>
  </main>;
}
